// Function to get random channels
export function getRandomChannels(count: number): ChannelData[] {
  const shuffled = [...channelsData].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

// Function to get channels by category
export function getChannelsByCategory(category: ChannelData['category'], count?: number): ChannelData[] {
  const filtered = channelsData.filter(ch => ch.category === category);
  if (count) {
    return filtered.slice(0, count);
  }
  return filtered;
}
